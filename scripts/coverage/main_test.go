package main

import "testing"

func TestExclusions(t *testing.T) {
	if !excluded("cmd/server/main.go", []byte(apiEntrypoint)) || !excluded("cmd/server/main.go", []byte(mocksEntrypoint)) {
		t.Fatal("wiring must be excluded")
	}
	if excluded("cmd/server/main.go", []byte(apiEntrypoint+"\nfunc business() {}")) || excluded("cmd/other/main.go", []byte(apiEntrypoint)) {
		t.Fatal("business code excluded")
	}
	if !excluded("generated.go", []byte("// Code generated by tool. DO NOT EDIT.\npackage generated")) || excluded("normal.go", []byte("// Code generated?\npackage normal")) {
		t.Fatal("generated marker")
	}
}
